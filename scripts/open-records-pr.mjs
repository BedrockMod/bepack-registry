#!/usr/bin/env node
import { readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { parseArgs } from 'node:util';
import { GitHubClient } from '../lib/github.mjs';
import { HttpsDownloader } from '../lib/download.mjs';
import { RegistryError, codes } from '../lib/errors.mjs';

const options = {
  base: { type: 'string', default: 'main' },
  summary: { type: 'string' },
  help: { type: 'boolean', default: false },
};

function usage() {
  return 'Usage: node scripts/open-records-pr.mjs [--base main] [--summary <file>]\\n'
    + 'Commits sources/releases/withdrawals changes to a bot branch and opens a pull request.\\n'
    + 'Requires GITHUB_TOKEN (App installation token), GITHUB_REPOSITORY, GITHUB_SERVER_URL.';
}

function git(args, options = {}) {
  return execFileSync('git', args, {
    encoding: options.encoding ?? 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    stdio: options.stdio ?? ['ignore', 'pipe', 'pipe'],
    env: { ...process.env, GIT_TERMINAL_PROMPT: '0' },
  });
}

function required(name) {
  const value = process.env[name];
  if (!value) throw new RegistryError(codes.CONFIG, `${name} is not configured`);
  return value;
}

async function main() {
  const values = parseArgs({ options }).values;
  if (values.help) {
    process.stdout.write(`${usage()}\\n`);
    return;
  }
  const token = required('GITHUB_TOKEN');
  const repository = required('GITHUB_REPOSITORY');
  const server = process.env.GITHUB_SERVER_URL ?? 'https://github.com';
  const base = values.base;

  const status = git(['status', '--porcelain', '--untracked-files=all', '--', 'sources', 'releases', 'withdrawals']);
  if (!status.trim()) {
    process.stdout.write(`${JSON.stringify({ ok: true, changed: false })}\\n`);
    return;
  }
  const changed = status.split('\n').filter(Boolean);
  for (const line of changed) {
    const file = line.slice(3).trim();
    if (!/^(sources|releases|withdrawals)\//u.test(file)) {
      throw new RegistryError(codes.ARGUMENT, `Refusing to commit unexpected path: ${file}`);
    }
  }

  const branch = `bot/records-${Date.now()}`;
  git(['config', 'user.name', 'bepack-registry-bot[bot]']);
  git(['config', 'user.email', 'bepack-registry-bot[bot]@users.noreply.github.com']);
  git(['checkout', '-b', branch]);
  git(['add', '--', 'sources', 'releases', 'withdrawals']);
  git(['commit', '-m', 'chore: sync verified pack records']);
  const auth = Buffer.from(`x-access-token:${token}`, 'utf8').toString('base64');
  git([
    '-c', `http.extraheader=AUTHORIZATION: basic ${auth}`,
    'push', 'origin', `${branch}:${branch}`,
  ]);

  let body = 'Verified records generated by the registry sync workflow. The record files are append-only; details are checked by CI before merge.';
  if (values.summary) {
    const summaryText = await readFile(values.summary, 'utf8');
    body += `\n\n\`\`\`json\n${summaryText.trim().slice(0, 12000)}\n\`\`\``;
  }
  const github = new GitHubClient({ token, downloader: new HttpsDownloader() });
  const pull = await github.createPullRequest(repository, {
    title: 'chore: sync verified pack records',
    head: branch,
    base,
    body,
  });
  process.stdout.write(`${JSON.stringify({ ok: true, changed: true, branch, pull_request: pull.number, url: pull.html_url })}\\n`);
}

main().catch((error) => {
  process.stderr.write(`${JSON.stringify({ ok: false, error: { code: error.code ?? codes.INTERNAL, message: error.message } })}\n`);
  process.exitCode = error.exitCode ?? 1;
});
